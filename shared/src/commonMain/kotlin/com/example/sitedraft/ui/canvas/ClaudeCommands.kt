package com.example.sitedraft.ui.canvas

import kotlinx.serialization.Serializable
import kotlinx.serialization.descriptors.PolymorphicKind
import kotlinx.serialization.descriptors.PrimitiveKind
import kotlinx.serialization.descriptors.SerialDescriptor
import kotlinx.serialization.descriptors.SerialKind
import kotlinx.serialization.descriptors.StructureKind
import kotlinx.serialization.json.Json
import kotlinx.serialization.json.JsonArray
import kotlinx.serialization.json.JsonElement
import kotlinx.serialization.json.JsonObject
import kotlinx.serialization.json.JsonPrimitive
import kotlinx.serialization.json.buildJsonArray
import kotlinx.serialization.json.buildJsonObject
import kotlinx.serialization.json.put
import kotlinx.serialization.json.putJsonArray

/**
 * Claude's commands (Dan, Nov 25 2026: "the app runs Claude's commands"). Claude does not get its
 * own copy of the drawing code: it sends the app's own [DrawingEvent]s - the same events a tap or a
 * panel button sends - written as `{"action": "AddWall", "args": {"lengthPx": 120.0}}`. The open
 * app runs them through [DrawingManager.runForClaude] (see cloud/ClaudeBridge.kt), so every
 * feature in the app is there for Claude the day it is added; a new event shows up in [catalog]
 * (and the connector's list_actions, generated by ConnectorExportTest) by itself.
 *
 * Values: points ([androidx.compose.ui.geometry.Offset]) are "x,y" in world pixels (canvas
 * space, x east, y south), sizes "w,h", colours Compose's packed Long; lengths named ...Px are world
 * pixels, ...In inches. The project's scale says how many world pixels make a foot.
 */
object ClaudeCommands {
    const val PREFIX = "com.example.sitedraft.ui.canvas.DrawingEvent."

    /**
     * Events Claude does not send: they carry whole files (pictures, PDF pages, DXF contents) or
     * open a dialog or a file on the device rather than change the drawing, or only make sense
     * for a pen on the screen.
     */
    val notForClaude: Set<String> = setOf(
        "ImportImage", "ImportPdf", "ImportDxf", "AddWallArt", "AddWallpaper",
        "ExportPdf", "Print", "ExportDxf", "ExportSheetSet",
        "StylusButtonErase", "ToggleStylusOnlyDrawing", "SetViewportSize"
    )

    val json = Json {
        classDiscriminator = "type"
        isLenient = true
        encodeDefaults = true
    }

    @Serializable
    data class Action(val action: String, val args: JsonObject = JsonObject(emptyMap()))

    /** What one batch did: how many events ran, the first error, what the app said, the states either side. */
    class RunOutcome(
        val ran: Int,
        val error: String?,
        val notes: List<String>,
        val before: CanvasState,
        val after: CanvasState
    )

    private val subclassDescriptors: List<SerialDescriptor> by lazy {
        val sub = DrawingEvent.serializer().descriptor.getElementDescriptor(1)
        (0 until sub.elementsCount).map { sub.getElementDescriptor(it) }
    }

    /** Every event name the app has (short names, e.g. "AddWall"). */
    val allNames: List<String> by lazy { subclassDescriptors.map { it.serialName.removePrefix(PREFIX) } }

    /**
     * Actions that hand over a whole settings object, and where the current one lives. Claude sends only
     * the fields it means to change; they're laid over the project's current settings, so a field left
     * out keeps its value instead of going back to the default (Nov 25: SetBuilding with only doorHeadIn
     * would have reset every other building input).
     */
    private val mergedArgs: Map<String, Pair<String, (CanvasState) -> JsonElement>> = mapOf(
        "SetBuilding" to ("settings" to { s -> json.encodeToJsonElement(BuildingSettings.serializer(), s.building) }),
        "UpdateProjectInfo" to ("info" to { s -> json.encodeToJsonElement(ProjectInfo.serializer(), s.projectInfo) })
    )

    /** [over] laid on [base]: objects merge field by field (all the way down), anything else in [over] wins. */
    internal fun mergeJson(base: JsonElement, over: JsonElement): JsonElement =
        if (base is JsonObject && over is JsonObject) JsonObject(base + over.mapValues { (k, v) -> base[k]?.let { mergeJson(it, v) } ?: v })
        else over

    /** One command as the app's event; throws [IllegalArgumentException] with a reason Claude can act on. */
    fun decode(action: Action, current: CanvasState? = null): DrawingEvent {
        val name = action.action.trim().removePrefix(PREFIX)
        require(name in allNames) { "Unknown action '$name'. list_actions has every action the app has." }
        require(name !in notForClaude) { "'$name' isn't available to Claude (it needs a file or the screen)." }
        val args = mergedArgs[name]?.let { (arg, of) ->
            val given = action.args[arg]
            if (current != null && given != null) action.args + (arg to mergeJson(of(current), given)) else null
        } ?: action.args
        val obj = JsonObject(args + ("type" to JsonPrimitive(PREFIX + name)))
        return try {
            json.decodeFromJsonElement(DrawingEvent.serializer(), obj)
        } catch (e: Exception) {
            throw IllegalArgumentException("'$name': ${e.message?.lineSequence()?.firstOrNull() ?: "its args don't fit"}", e)
        }
    }

    /** A batch, decoded all at once so nothing runs when any one of them is wrong. */
    fun decodeAll(actionsJson: String, current: CanvasState? = null): List<DrawingEvent> {
        val list = json.decodeFromString(kotlinx.serialization.builtins.ListSerializer(Action.serializer()), actionsJson)
        return list.mapIndexed { i, a ->
            try {
                decode(a, current)
            } catch (e: IllegalArgumentException) {
                throw IllegalArgumentException("Action ${i + 1}: ${e.message}", e)
            }
        }
    }

    // ------------------------------------------------------------------ the list of actions

    /**
     * Every action Claude can send, with its arguments and their types, read from the app's own
     * event classes. [docs] (event name to its comment in DrawingManager.kt) is added when known.
     */
    fun catalog(docs: Map<String, String> = emptyMap()): JsonArray = buildJsonArray {
        for (d in subclassDescriptors) {
            val name = d.serialName.removePrefix(PREFIX)
            if (name in notForClaude) continue
            add(buildJsonObject {
                put("action", name)
                docs[name]?.let { put("about", it) }
                putJsonArray("args") {
                    for (j in 0 until d.elementsCount) add(buildJsonObject {
                        put("name", d.getElementName(j))
                        put("type", typeOf(d.getElementDescriptor(j), 0))
                        if (d.isElementOptional(j)) put("optional", true)
                    })
                }
            })
        }
    }

    private fun short(serialName: String) = serialName.removeSuffix("?").substringAfterLast('.')

    private fun typeOf(d: SerialDescriptor, depth: Int): JsonElement {
        val nullable = d.isNullable
        val base: JsonElement = when (val k = d.kind) {
            is PrimitiveKind -> JsonPrimitive(
                when (short(d.serialName)) {
                    "Offset" -> "point \"x,y\" (world px)"
                    "Size" -> "size \"w,h\" (world px)"
                    else -> when (k) {
                        PrimitiveKind.STRING -> "text"
                        PrimitiveKind.BOOLEAN -> "true/false"
                        PrimitiveKind.INT, PrimitiveKind.LONG, PrimitiveKind.SHORT, PrimitiveKind.BYTE ->
                            if (short(d.serialName) == "Color") "colour (packed Long)" else "whole number"
                        else -> "number"
                    }
                }
            )
            SerialKind.ENUM -> buildJsonObject {
                putJsonArray("oneOf") { for (i in 0 until d.elementsCount) add(JsonPrimitive(d.getElementName(i))) }
            }
            StructureKind.LIST -> buildJsonObject { put("listOf", typeOf(d.getElementDescriptor(0), depth + 1)) }
            StructureKind.MAP -> buildJsonObject { put("map", typeOf(d.getElementDescriptor(1), depth + 1)) }
            StructureKind.OBJECT -> JsonPrimitive("{}")
            StructureKind.CLASS -> if (depth >= 3) JsonPrimitive(short(d.serialName)) else buildJsonObject {
                put("object", short(d.serialName))
                putJsonArray("fields") {
                    for (i in 0 until d.elementsCount) add(buildJsonObject {
                        put("name", d.getElementName(i))
                        put("type", typeOf(d.getElementDescriptor(i), depth + 1))
                        if (d.isElementOptional(i)) put("optional", true)
                    })
                }
            }
            PolymorphicKind.SEALED -> {
                val subs = d.getElementDescriptor(1)
                buildJsonObject {
                    put("kind", short(d.serialName))
                    put("note", "an object with \"type\": the full name of one of these, plus its fields")
                    putJsonArray("oneOf") {
                        for (i in 0 until subs.elementsCount) {
                            val s = subs.getElementDescriptor(i)
                            add(buildJsonObject {
                                put("type", s.serialName)
                                if (depth < 3) putJsonArray("fields") {
                                    for (j in 0 until s.elementsCount) add(buildJsonObject {
                                        put("name", s.getElementName(j))
                                        put("type", typeOf(s.getElementDescriptor(j), depth + 1))
                                        if (s.isElementOptional(j)) put("optional", true)
                                    })
                                }
                            })
                        }
                    }
                }
            }
            else -> JsonPrimitive(short(d.serialName))
        }
        return if (nullable && base is JsonPrimitive) JsonPrimitive("${base.content} or null")
        else if (nullable) JsonObject((base as JsonObject) + ("nullable" to JsonPrimitive(true)))
        else base
    }

    // ------------------------------------------------------------------ what changed

    private fun describe(e: DrawingElement): JsonObject = buildJsonObject {
        put("id", e.id)
        put("kind", e::class.simpleName ?: "Element")
        when (e) {
            is DrawingElement.Symbol -> {
                put("name", e.symbolName)
                put("category", e.category)
                put("center", "${e.center.x},${e.center.y}")
                put("size", "${e.size.width},${e.size.height}")
                if (e.rotation != 0f) put("rotation", e.rotation)
            }
            is DrawingElement.Text -> put("text", e.text.take(80))
            is DrawingElement.Line -> {
                put("from", "${e.start.x},${e.start.y}")
                put("to", "${e.end.x},${e.end.y}")
            }
            else -> {}
        }
        e.layerId?.let { put("layer", it) }
    }

    /** The result Claude gets back for a batch: what ran, what the app said, and what changed. */
    fun result(o: RunOutcome, total: Int, saved: Boolean, device: String): JsonObject {
        val beforeById = o.before.elements.associateBy { it.id }
        val afterById = o.after.elements.associateBy { it.id }
        val added = o.after.elements.filter { it.id !in beforeById }
        val removed = o.before.elements.filter { it.id !in afterById }
        val changed = o.after.elements.filter { e -> beforeById[e.id]?.let { it != e } == true }
        val cap = 60
        return buildJsonObject {
            put("device", device)
            put("project", o.after.projectName)
            put("ran", o.ran)
            put("of", total)
            o.error?.let { put("error", it) }
            if (o.notes.isNotEmpty()) putJsonArray("appSaid") { o.notes.forEach { add(JsonPrimitive(it)) } }
            put("saved", saved)
            putJsonArray("added") { added.take(cap).forEach { add(describe(it)) } }
            if (added.size > cap) put("addedMore", added.size - cap)
            putJsonArray("removed") { removed.take(cap).forEach { add(JsonPrimitive(it.id)) } }
            if (removed.size > cap) put("removedMore", removed.size - cap)
            putJsonArray("changed") { changed.take(cap).forEach { add(describe(it)) } }
            if (changed.size > cap) put("changedMore", changed.size - cap)
            put("elements", o.after.elements.size)
            put("tool", o.after.currentTool.name)
            val sel = o.after.selectedElementIds.ifEmpty { setOfNotNull(o.after.selectedElementId) }
            putJsonArray("selected") { sel.forEach { add(JsonPrimitive(it)) } }
            o.after.pendingPlacement?.let { put("waitingToPlace", it.label) }
            put("activeLayer", o.after.activeLayerId ?: "")
            put("pxPerFoot", o.after.scale.ratio)
            put("units", o.after.unitSystem.name)
            put("zoom", o.after.zoom)
            put("pan", "${o.after.pan.x},${o.after.pan.y}")
        }
    }
}
