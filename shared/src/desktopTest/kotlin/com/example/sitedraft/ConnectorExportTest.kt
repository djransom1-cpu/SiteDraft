/**
 * Writes what the Site Draft MCP connector (functions-mcp/sitedraft/) needs to stay in step with the
 * app, straight from the app's own code, so nothing is typed twice:
 *
 * - catalog.json: every plan symbol by category with its footprint (width along the wall x depth,
 *   inches), the property keys the app reads, and the scale defaults.
 * - fixtures/empty-project.json: a new project exactly as the app saves it.
 * - fixtures/sample-elements.json: one of each element the connector writes, as the app encodes it.
 *
 * Run by the normal desktop test task; the files are committed with the connector.
 */
class ConnectorExportTest {
    /** The app's own project encoder (DrawingManager.json). */
    private val appJson = Json { prettyPrint = true; ignoreUnknownKeys = true }
    private val outDir = File("../functions-mcp/sitedraft").apply { mkdirs() }

    @Test
    fun `export the symbol catalog`() {
        val cats = linkedMapOf(
            PlanSymbols.WALLS to PlanSymbols.walls,
            PlanSymbols.DOORS_WINDOWS to PlanSymbols.doorsWindows,
            PlanSymbols.CABINETS to PlanSymbols.cabinets,
            PlanSymbols.APPLIANCES to Appliances.appliances,
            PlanSymbols.HOODS to Appliances.hoods,
            PlanSymbols.FIXTURES to PlanSymbols.fixtures,
            PlanSymbols.SHOWERS to Shower.library,
            PlanSymbols.STAIRS to Stairs.library,
            PlanSymbols.OUTDOOR to PlanSymbols.outdoor,
            PlanSymbols.CLOSET to PlanSymbols.closet,
            PlanSymbols.FURNITURE to PlanSymbols.furniture,
        )
        val catalog = buildJsonObject {
            put("note", "Generated by ConnectorExportTest from the app's code. Do not edit by hand.")
            putJsonObject("defaults") {
                put("pxPerFoot", CanvasState().scale.ratio)
                put("unitSystem", CanvasState().unitSystem.name)
                // Read for windows saved without a sill of their own (old ones): stays 36".
                put("windowSillIn", 36f)
                // A new window: head lined up with the door head.
                put("newWindowSillIn", PlanSymbols.NEW_WINDOW_SILL_IN)
                put("windowHeightIn", 48f)
                put("doorHeightIn", 80f)
                put("upperHeightIn", PlanSymbols.DEFAULT_UPPER_HEIGHT_IN)
                put("pantryHeightIn", PlanSymbols.PANTRY_HEIGHT_IN)
                put("defaultWallLengthIn", PlanSymbols.DEFAULT_WALL_LENGTH_IN)
            }
            putJsonObject("props") {
                put("hingeRight", PlanSymbols.PROP_HINGE_RIGHT)
                put("sillIn", PlanSymbols.PROP_SILL_IN)
                put("heightIn", PlanSymbols.PROP_HEIGHT_IN)
                put("front", PlanSymbols.PROP_FRONT)
                put("doors", PlanSymbols.PROP_DOORS)
                put("style", PlanSymbols.PROP_STYLE)
                put("hardware", PlanSymbols.PROP_HARDWARE)
                put("upperHeightIn", PlanSymbols.PROP_UPPER_HEIGHT_IN)
                put("topIn", PlanSymbols.PROP_TOP_IN)
                put("sinks", PlanSymbols.PROP_SINKS)
                put("overhang", PlanSymbols.PROP_OVERHANG)
                put("overhangIn", PlanSymbols.PROP_OVERHANG_IN)
                put("posFromEnd", OpeningPosition.PROP_FROM_END)
                put("posToCenter", OpeningPosition.PROP_TO_CENTER)
                put("posOutside", OpeningPosition.PROP_OUTSIDE)
            }
            putJsonObject("labels") {
                putJsonArray("front") { PlanSymbols.frontLabels.forEach { add(JsonPrimitive(it)) } }
                putJsonArray("style") { PlanSymbols.styleLabels.forEach { add(JsonPrimitive(it)) } }
                putJsonArray("hardware") { PlanSymbols.hardwareLabels.forEach { add(JsonPrimitive(it)) } }
            }
            putJsonObject("counterSinks") { PlanSymbols.counterSinks.forEach { put(it, true) } }
            putJsonObject("categories") {
                for ((cat, names) in cats) putJsonArray(cat) { names.forEach { add(JsonPrimitive(it)) } }
            }
            putJsonObject("footprints") {
                for ((name, wd) in PlanSymbols.footprintInches) put(name, JsonArray(listOf(JsonPrimitive(wd.first), JsonPrimitive(wd.second))))
            }
            // Levels and layers (Building.kt): the defaults, and samples the connector's layers.js is checked against.
            put("building", buildBuilding())
        }
        val f = File(outDir, "catalog.json")
        f.writeText(Json { prettyPrint = true }.encodeToString(kotlinx.serialization.json.JsonObject.serializer(), catalog) + "\n")
        assertTrue(f.length() > 1000)
    }

    /** Defaults and samples of the levels and layers, for layers.js to be checked against. */
    private fun buildBuilding(): kotlinx.serialization.json.JsonObject {
        val all = Json { encodeDefaults = true }
        val two = com.example.sitedraft.ui.canvas.BuildingSettings(upperFloors = listOf(com.example.sitedraft.ui.canvas.UpperFloor("Second floor", 1310f)))
        val crawl = com.example.sitedraft.ui.canvas.BuildingSettings(foundation = com.example.sitedraft.ui.canvas.FoundationType.CRAWL)
        val slab = com.example.sitedraft.ui.canvas.BuildingSettings(foundation = com.example.sitedraft.ui.canvas.FoundationType.SLAB)
        fun levels(s: com.example.sitedraft.ui.canvas.BuildingSettings) = JsonArray(com.example.sitedraft.ui.canvas.Building.levels(s).map { l ->
            buildJsonObject { put("id", l.id); put("name", l.name); put("kind", l.kind.name); put("elevationIn", l.elevationIn); put("note", l.note) }
        })
        fun layers(s: com.example.sitedraft.ui.canvas.BuildingSettings) =
            all.encodeToJsonElement(ListSerializer(com.example.sitedraft.ui.canvas.Layer.serializer()), com.example.sitedraft.ui.canvas.Building.defaultLayers(s))
        val samples = listOf("default" to com.example.sitedraft.ui.canvas.BuildingSettings(), "twoFloors" to two, "crawl" to crawl, "slab" to slab)
        return buildJsonObject {
            put("defaults", all.encodeToJsonElement(com.example.sitedraft.ui.canvas.BuildingSettings.serializer(), com.example.sitedraft.ui.canvas.BuildingSettings()))
            put("floor1Plan", com.example.sitedraft.ui.canvas.Building.FLOOR1_PLAN)
            put("floor1Cabinets", com.example.sitedraft.ui.canvas.Building.FLOOR1_CABINETS)
            put("floor1Furniture", com.example.sitedraft.ui.canvas.Building.FLOOR1_FURNITURE)
            putJsonObject("samples") {
                for ((name, s) in samples) putJsonObject(name) {
                    put("settings", all.encodeToJsonElement(com.example.sitedraft.ui.canvas.BuildingSettings.serializer(), s))
                    put("levels", levels(s))
                    put("layers", layers(s))
                }
            }
        }
    }

    @Test
    fun `export an empty project and one of each element`() {
        File(outDir, "fixtures").mkdirs()
        val empty = CanvasState(projectName = "Example")
        File(outDir, "fixtures/empty-project.json").writeText(appJson.encodeToString(CanvasState.serializer(), empty) + "\n")

        val white = Color.White
        val wall = DrawingElement.Symbol(id = "wall-1", symbolName = "2x4 Wall", category = PlanSymbols.WALLS, center = Offset(100f, 9.375f),
            size = Size(200f, 18.75f), color = white, properties = mapOf("widthInches" to 48f, "depthInches" to 4.5f))
        val door = DrawingElement.Symbol(id = "door-1", symbolName = "Door 3'-0\"", category = PlanSymbols.DOORS_WINDOWS, center = Offset(60f, -65.625f),
            size = Size(150f, 150f), color = white, rotation = 90f,
            properties = mapOf("widthInches" to 36f, "depthInches" to 36f, PlanSymbols.PROP_HEIGHT_IN to 80f, PlanSymbols.PROP_HINGE_RIGHT to 1f))
        val cab = DrawingElement.Symbol(id = "cab-1", symbolName = "Base 24\"", category = PlanSymbols.CABINETS, center = Offset(50f, 68.75f),
            size = Size(100f, 100f), color = white, rotation = 180f,
            properties = mapOf("widthInches" to 24f, "depthInches" to 24f, PlanSymbols.PROP_FRONT to 2f))
        val text = DrawingElement.Text(id = "text-1", text = "Kitchen\n12' x 10'", topLeft = Offset(10f, 20f), fontSize = 25f, color = white)
        val dim = DrawingElement.Dimension(id = "dim-1", start = Offset(0f, 0f), end = Offset(100f, 0f), value = 2f, unit = UnitSystem.IMPERIAL,
            format = DimensionFormat.ARCHITECTURAL, color = white, offset = -30f, ownerId = "plan")
        val elev = DrawingElement.ElevationView(id = "elev-1", spec = ElevationSpec(wallId = "wall-1", side = ViewerSide.BELOW),
            origin = Offset(0f, 600f), size = Size(200f, 400f), color = Color.Black)
        val pdf = DrawingElement.Pdf(id = "pdf-1", pages = listOf(ImageBitmap(2, 2)), topLeft = Offset(0f, 0f), size = Size(2f, 2f), locked = true, opacity = 0.6f)
        val samples = listOf<DrawingElement>(wall, door, cab, text, dim, elev, pdf)
        File(outDir, "fixtures/sample-elements.json").writeText(
            appJson.encodeToString(ListSerializer(DrawingElement.serializer()), samples) + "\n"
        )
        // And a whole project holding them, as the app saves it.
        File(outDir, "fixtures/sample-project.json").writeText(
            appJson.encodeToString(CanvasState.serializer(), CanvasState(projectName = "Sample", elements = samples)) + "\n"
        )
    }
}
